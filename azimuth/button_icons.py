_CACHE = {}


def _tables(lang):
    if lang not in _CACHE:
        exact = {i18n.tr(text, lang): name for text, name in TEXT_ICONS.items()}
        rules = tuple((i18n.tr(words, lang), name) for words, name in RULES)
        _CACHE[lang] = (exact, rules)
    return _CACHE[lang]


def icon_name(text, lang=None):
    """The glyph of a button showing text (in the language lang, by default that of the program), or None."""
    text = (text or '').replace('&', '').strip()
    if not text:
        return None
    exact, rules = _tables(lang or i18n.LANG)
    if text in exact:
        return exact[text]
    for words, name in rules:
        if (text.startswith(words + ' ') or text.startswith(words + '…') or text.startswith(words + ':')
                or text == words):
            return name
    return None
