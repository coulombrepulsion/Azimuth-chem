# ------------------------------------------------------- one operation
def axis_of(R):
    a = [R[2][1] - R[1][2], R[0][2] - R[2][0], R[1][0] - R[0][1]]
    l = js_hypot(*a)
    if l > 1e-5:
        return [x / l for x in a]
    B = [[R[i][j] + (1 if i == j else 0) for j in range(3)] for i in range(3)]
    best, bl = B[0], 0
    for j in range(3):
        c = [B[0][j], B[1][j], B[2][j]]
        cl = js_hypot(*c)
        if cl > bl:
            bl, best = cl, c
    return nrm(best)


def frac(th):
    for n in range(1, 13):
        k = th / (2 * PI) * n
        if abs(k - js_round(k)) < 1e-4:
            return n, int(js_round(k))
    return 0, 0


def canon(v, ref) -> bool:
    if ref:
        return dot(v, ref) < -1e-6
    for x in v:
        if abs(x) > 1e-6:
            return x < 0
    return False


def info(M, ref=None) -> dict:
    """Type of an operation: {'t': 'E'|'C'|'i'|'s'|'S', 'n', 'k', 'ax'} as v1.0 info()."""
    d = det(M)
    if d > 0:
        c = max(-1.0, min(1.0, (tr(M) - 1) / 2))
        th0 = acos(c)
        if th0 < 1e-5:
            return {"t": "E"}
        ax, th = axis_of(M), th0
        if abs(th0 - PI) > 1e-5 and canon(ax, ref):
            ax = [-x for x in ax]
            th = 2 * PI - th0
        elif abs(th0 - PI) <= 1e-5 and canon(ax, ref):
            ax = [-x for x in ax]
        n, k = frac(th)
        return {"t": "C", "n": n, "k": k, "ax": ax}
    N = [[-x for x in r] for r in M]
    c = max(-1.0, min(1.0, (tr(N) - 1) / 2))
    ph0 = acos(c)
    if ph0 < 1e-5:
        return {"t": "i"}
    ax = axis_of(N)
    if abs(ph0 - PI) < 1e-5:
        if canon(ax, None):
            ax = [-x for x in ax]
        return {"t": "s", "ax": ax}
    ph = ph0
    if canon(ax, ref):
        ax = [-x for x in ax]
        ph = 2 * PI - ph0
    th = ph - PI
    if th < 0:
        th += 2 * PI
    n, k = frac(th)
    if n % 2 == 1 and k % 2 == 0:
        k += n
    return {"t": "S", "n": n, "k": k, "ax": ax}


def _parallel(u, v) -> bool:
    return abs(abs(dot(u, v)) - 1) < 1e-4


# ------------------------------------------------------------- classes
def classes(G):
    index = {key(g): i for i, g in enumerate(G)}
    used = [False] * len(G)
    out = []
    for i in range(len(G)):
        if used[i]:
            continue
        cl = {}
        for h in G:
            j = index.get(key(mm(mm(h, G[i]), tp(h))), -1)
            if j >= 0:
                cl[j] = True
        mem = list(cl)
        for j in mem:
            used[j] = True
        out.append({"ops": [G[j] for j in mem], "idx": mem})
    return out


def axes_of(G):
    ax = []
    for M in G:
        f = info(M)
        if f["t"] != "C":
            continue
        found = next((a for a in ax if _parallel(a["v"], f["ax"])), None)
        if found is None:
            found = {"v": f["ax"], "n": 1}
            ax.append(found)
        if f["n"] > found["n"]:
            found["n"] = f["n"]
    return ax


def identify(G) -> dict:
    I = [info(M) for M in G]
    has_i = any(f["t"] == "i" for f in I)
    sig = [f for f in I if f["t"] == "s"]
    ax = axes_of(G)
    high = [a for a in ax if a["n"] >= 3]
    if len(high) >= 2:
        if any(a["n"] == 5 for a in ax):
            return {"name": "Ih" if has_i else "I", "pa": None}
        if any(a["n"] == 4 for a in ax):
            return {"name": "Oh" if has_i else "O", "pa": None}
        if has_i:
            return {"name": "Th", "pa": None}
        return {"name": "Td" if sig else "T", "pa": None}
    if not ax:
        return {"name": "Cs" if sig else "Ci" if has_i else "C1", "pa": None}
    n = max(a["n"] for a in ax)
    cand = [a for a in ax if a["n"] == n]
    pa, best = cand[0]["v"], -1
    for c in cand:
        along = sum(1 for f in I if f.get("ax") and _parallel(f["ax"], c["v"]))
        perp = sum(1 for a in ax if a["n"] >= 2 and abs(dot(a["v"], c["v"])) < 1e-4)
        sc = along * 10 + perp
        if sc > best:
            best, pa = sc, c["v"]
    perp_c2 = sum(1 for a in ax if a["n"] >= 2 and abs(dot(a["v"], pa)) < 1e-4)
    sh = any(_parallel(s["ax"], pa) for s in sig)
    sv = any(abs(dot(s["ax"], pa)) < 1e-4 for s in sig)
    if perp_c2 >= n:
        return {"name": f"D{n}{'h' if sh else 'd' if sv else ''}", "pa": pa, "n": n}
    if sh:
        return {"name": f"C{n}h", "pa": pa, "n": n}
    if sv:
        return {"name": f"C{n}v", "pa": pa, "n": n}
    if any(f["t"] == "S" and _parallel(f["ax"], pa) for f in I):
        return {"name": f"S{2 * n}", "pa": pa, "n": n}
    return {"name": f"C{n}", "pa": pa, "n": n}


# -------------------------------------------------------- class labels
_SUB = dict(zip("0123456789", "₀₁₂₃₄₅₆₇₈₉"))
_SUPS = dict(zip("23456789", "²³⁴⁵⁶⁷⁸⁹"))


def subs(s) -> str:
    return "".join(_SUB.get(c, c) for c in str(s))


def sup(k) -> str:
    return "".join(_SUPS.get(c, c) for c in str(k))


_AXN = (("x", [1, 0, 0]), ("y", [0, 1, 0]), ("z", [0, 0, 1]))


def ax_letter(v):
    for l, a in _AXN:
        if _parallel(v, a):
            return l
    return None


def plane_name(n):
    l = ax_letter(n)
    return {"x": "yz", "y": "xz", "z": "xy"}[l] if l else None


def atoms_on_axis(v, atoms) -> int:
    k = 0
    for a in atoms:
        p = a["p"]
        if js_hypot(*p) < 1e-3 or js_hypot(*cross(p, v)) < 1e-3:
            k += 1
    return k


def atoms_in_plane(n, atoms) -> int:
    return sum(1 for a in atoms if abs(dot(a["p"], n)) < 1e-3)


def _sort(arr, cmp):
    arr.sort(key=functools.cmp_to_key(cmp))


def _cmp_num(x) -> int:
    return (x > 0) - (x < 0)


