ORB = ("s", "px", "py", "pz", "dz2", "dx2y2", "dxy", "dxz", "dyz")
_s6, _s2 = 1 / math.sqrt(6), 1 / 1.4142135623730951  # 1/Math.sqrt(6), 1/Math.SQRT2
DB = [[[-_s6, 0, 0], [0, -_s6, 0], [0, 0, 2 * _s6]], [[_s2, 0, 0], [0, -_s2, 0], [0, 0, 0]],
      [[0, _s2, 0], [_s2, 0, 0], [0, 0, 0]], [[0, 0, _s2], [0, 0, 0], [_s2, 0, 0]], [[0, 0, 0], [0, 0, _s2], [0, _s2, 0]]]


def frob(a, b):
    s = 0.0
    for i in range(3):
        for j in range(3):
            s += a[i][j] * b[i][j]
    return s


def rep9(Mt):
    D = [[0.0] * 9 for _ in range(9)]
    D[0][0] = 1.0
    for i in range(3):
        for j in range(3):
            D[1 + i][1 + j] = Mt[i][j]
    T = tp(Mt)
    for j in range(5):
        B = mm(mm(Mt, DB[j]), T)
        for i in range(5):
            D[4 + i][4 + j] = frob(DB[i], B)
    return D


def orb_irreps(G, B):
    ct, h, Qt = B["ct"], len(G), tp(B["Q"])
    reps = [rep9(mm(mm(Qt, M), B["Q"])) for M in G]
    out = []
    for i in range(9):
        w = []
        for ir in ct["irreps"]:
            f = (ir["dim"] / 2 if ir["merged"] else ir["dim"]) / h
            s = 0.0
            for g in range(len(G)):
                s += ir["chi"][B["opCol"][g]] * reps[g][i][i]
            w.append(f * s)
        best = [j for j, x in enumerate(w) if x > 1e-6]
        out.append({"irr": best[0] if len(best) == 1 else -1, "w": w})
    return out


# ----------------------------------------------------------- Gamma
def fixed_atoms(M, atoms):
    return [i for i, a in enumerate(atoms) if hyp3(mv(M, a["p"]), a["p"]) < 2e-3]


def reduce_rep(chi, ct):
    h = 0
    for c in ct["classes"]:
        h += c["n"]
    out = []
    for ir in ct["irreps"]:
        s = 0.0
        for j, c in enumerate(ct["classes"]):
            s += c["n"] * chi[j] * ir["chi"][j]
        out.append(js_round(s / h / (2 if ir["merged"] else 1) * 1e6) / 1e6)
    return out


def gamma_all(G, atoms, B) -> dict:
    ct, Qt = B["ct"], tp(B["Q"])
    reps = [mm(mm(B["Q"], c["M"]), Qt) for c in ct["classes"]]
    nfix = [len(fixed_atoms(M, atoms)) for M in reps]
    contr = [js_round(tr(M) * 1e9) / 1e9 for M in reps]
    g3N = [n * contr[j] for j, n in enumerate(nfix)]
    gT = [tr(c["M"]) for c in ct["classes"]]
    gR = [det(c["M"]) * tr(c["M"]) for c in ct["classes"]]
    gQ = []
    for c in ct["classes"]:
        t, t2 = tr(c["M"]), tr(mm(c["M"], c["M"]))
        gQ.append((t * t + t2) / 2)
    n3N, nT, nR, nQ = (reduce_rep(x, ct) for x in (g3N, gT, gR, gQ))
    nV = [x - nT[i] - nR[i] for i, x in enumerate(n3N)]
    return {"nfix": nfix, "contr": contr, "g3N": g3N, "n3N": n3N, "nT": nT, "nR": nR, "nV": nV,
            "ir": [x > 0 for x in nT], "ra": [x > 0 for x in nQ]}


# ---------------------------------------- descent and multiplication
def correlation(P, H) -> list:
    """For every class of the parent group: surviving operations, target classes, rotation angles."""
    where = {}
    for ci, c in enumerate(H["cls"]):
        for o in c["ops"]:
            where[key(o)] = ci
    rows = []
    for pc in P["cls"]:
        tgt: dict = {}
        surv = 0
        sa = []
        for o in pc["ops"]:
            ci = where.get(key(o))
            if ci is not None:
                surv += 1
                tgt[ci] = tgt.get(ci, 0) + 1
                f = info(o, ZZ)
                if f.get("n"):
                    sa.append(int(js_round(360 * f["k"] / f["n"])))
        rows.append({"surv": surv, "tgt": list(tgt), "sa": list(dict.fromkeys(sa))})
    return rows


def op_list(H, L) -> list:
    """v1.0 opList: operations class by class, each class sorted by name."""
    names = op_names(L)
    index = {key(g): i for i, g in enumerate(H)}
    out = []
    for ci, c in enumerate(L["cls"]):
        arr = [{"h": index[key(M)], "name": names[key(M)]["name"], "ci": ci} for M in c["ops"]]
        arr.sort(key=lambda o: locale_key(o["name"]))
        out.append(arr)
    return [o for arr in out for o in arr]


def mult_table(H, ops) -> list:
    Ms = [H[o["h"]] for o in ops]
    index = {key(M): i for i, M in enumerate(Ms)}
    tab = []
    for a in ops:
        row = []
        A = H[a["h"]]
        for b in ops:
            P = mm(A, H[b["h"]])
            i = index.get(key(P))
            if i is None or frob_dist(Ms[i], P) >= 1e-6:
                i = find_op(Ms, P)
            row.append(i)
        tab.append(row)
    return tab


def frob_dist(g, M) -> float:
    d = 0.0
    for r in range(3):
        for c in range(3):
            x = g[r][c] - M[r][c]
            d += x * x
    return d
