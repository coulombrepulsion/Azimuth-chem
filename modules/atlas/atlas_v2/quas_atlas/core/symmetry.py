"""Point groups of molecular models: operations, classes, character tables.

HEADER
    Group-theory engine of the "Molecular symmetry" page (v1.0: symmetry.js,
    sections "линейная алгебра 3x3" ... "счётчики Г", "понижение симметрии",
    "таблица умножения").  Wilkinson convention, sections 1-8.

§1 THEORY
    A symmetry operation of a molecule is an orthogonal 3x3 matrix M that
    maps every nucleus onto a nucleus of the same element.  The operations
    generated by a few generators g_1..g_m form a finite group G (closure
    under multiplication); the subgroup that leaves a distorted model
    invariant is its stabiliser H.  Conjugacy classes {h g h^-1} partition G.
    An operation is classified from det M and tr M: det = +1 gives a proper
    rotation by theta, cos theta = (tr M - 1)/2, axis from the antisymmetric
    part; det = -1 gives -M, a proper rotation, so M is i (theta = 0), a
    reflection sigma (theta = pi) or an improper rotation S_n.  The point
    group follows from the set of axes and planes (Schoenflies flow chart).
    A character table is bound to the model by finding an orthogonal Q with
    Q T Q^T in G for every tabulated operation T (column j -> class).  Then
        n(Gamma) = (1/h) sum_g chi_Gamma(g) chi(g)               (reduction)
    gives the multiplicity of each irreducible representation in the
    representation spanned by atomic displacements (Gamma_3N, a fixed atom
    contributing tr M), translations (tr M), rotations (det M tr M) and
    quadratic functions ((tr M)^2 + tr M^2)/2; Gamma_vib = Gamma_3N - Gamma_T
    - Gamma_R.  Orbital symmetry: the projection weights of s, p, d functions
    (rep9: the 9x9 representation of M on s, p, d in the table's frame).

§2 ALGORITHM
    As in v1.0, function for function (names kept): closure (breadth-first,
    keys = matrix entries rounded to 1e-4), stabilizer, info, classes,
    identify, label_classes, op_names, lin_classes (C_inf_v / D_inf_h are
    represented by 12-fold rotations), align_ct / bind_ct, orb_irreps,
    gamma_all, correlation, multiplication table.

§3 APPLICATIONS
    Endpoints sym.group and sym.state (pages/symmetry.py).

§4 SPECIFICATION
    Every function returns what the v1.0 JavaScript function returns, with
    floating-point results bitwise equal to V8 (Chromium 141) on every
    platform: the only transcendental functions are sin, cos, acos and hypot,
    all taken from core.jsmath (V8-identical ports).  Tier: bitwise vs v1.0
    (tests/test_symmetry.py compares every model of the page and the
    descents with values recorded in Chromium).

§5 PROCEDURES -- below.
§6 IMPLEMENTATION NOTES
    * Lookups "G.findIndex(g => key(g) === key(m))" become dict lookups:
      keys within one group are unique (closure inserts each key once), so
      the first match is the only match.
    * find_op (nearest operation within 1e-6 in the Frobenius norm) is
      replaced by a key lookup only in the multiplication table, where the
      candidate is then verified with the same 1e-6 test (falls back to the
      full scan otherwise) -- identical result, h times faster.
    * String.prototype.localeCompare (ICU root collation) orders class and
      operation names in v1.0.  locale_key reproduces ICU for the alphabet
      of these labels (verified on every pair that occurs, §7).
    * JS objects become dicts; a key absent in JS (undefined) is absent here.
§7 TEST CASES (tests/test_symmetry.py)
    Oracles: |G| for every page group (C1 1 ... Ih 120); classes partition G
    and are closed under conjugation; sum over classes of n_c = h; the
    character-table orthogonality (sum_c n_c chi_i chi_j = h delta_ij for the
    non-merged irreps); Gamma_3N of CH4 = A1 + E + T1 + 3T2 and Gamma_vib =
    A1 + E + 2T2; H2O Gamma_vib = 2A1 + B1; the multiplication table is a
    Latin square.  Plus every page model vs Chromium (fixture symmetry.json).
§8 ERROR ANALYSIS
    Group elements are products of at most ~10 rotation matrices: entries
    carry errors of a few u.  All decisions use tolerances (1e-4 for keys and
    axis comparisons, 1e-5 for angles, 2e-3 Angstrom for atom matching) many
    orders of magnitude above these errors and below the smallest geometric
    differences of the models (>= 0.01), so the discrete results (group,
    classes, labels, binding) are exact; the continuous outputs (Q, weights)
    have errors of O(10u).
"""
